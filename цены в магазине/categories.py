def classify(name: str, source_category: str) -> tuple[str, str, str]:
    """Use source context first to keep e.g. apple shampoo out of fruit."""
    context = source_category.casefold()
    if re.search(r"растительн", context) or re.search(
        r"(?:молоко|сыр|десерт).*растительн|растительн.*(?:молоко|сыр|десерт)", name, re.I
    ):
        if re.search(r"молоко|напиток", name, re.I) or "растительное молоко" in context:
            return "Напитки", "Растительные напитки", "растительная альтернатива"
        if re.search(r"сыр|десерт", name, re.I):
            return "Особое питание", "Растительные альтернативы", "растительная альтернатива"
    if re.search(r"безалкогольн", name, re.I) and (
        "алкогол" in context or re.search(r"\b(?:напиток|вино|пиво|коктейль|сидр)\b", name, re.I)
    ):
        return "Напитки", "Безалкогольные альтернативы", "явное обозначение в названии"
    priority = next(((section, category) for section, category, pattern in SOURCE_RULES
                     if re.search(pattern, context)), None)
    # A breadcrumb's broad parent must not override its specific food leaf.
    protected = {"Зоотовары", "Детские товары", "Гигиена и косметика", "Бытовая химия",
                 "Непродовольственные товары", "Алкоголь", "Готовая еда и полуфабрикаты", "Особое питание"}
    if not priority or priority[0] not in protected:
        leaf = context.rsplit("/", 1)[-1].strip()
        leaf_priority = next(((section, category) for section, category, pattern in SOURCE_RULES
                              if re.search(pattern, leaf)), None)
        priority = leaf_priority or priority
    matching = [(section, category) for section, category, pattern in RULES
                if re.search(pattern, name, re.IGNORECASE)]
    nonfood_context = priority and priority[0] in {'Зоотовары', 'Детские товары', 'Гигиена и косметика',
                                                  'Бытовая химия', 'Непродовольственные товары'}
    if not nonfood_context:
        if re.search(r'напиток\s+кисломолочн', name, re.I):
            return 'Молочные продукты и яйца', 'Кисломолочные продукты', 'вид продукта в названии'
        if re.search(r'\bсмузи\b', name, re.I):
            return 'Напитки', 'Смузи', 'вид продукта в названии'
    if (priority and priority[0] in {"Непродовольственные товары", "Бытовая химия", "Гигиена и косметика"}
            and matching and matching[0][0] in {"Расходники", "Бытовая химия", "Гигиена и косметика"}):
        return *matching[0], "название расходника и непродовольственный раздел магазина"
    if priority and priority[0] in protected:
        for section, category in matching:
            if section == priority[0]:
                return section, category, "название и категория магазина"
        return *priority, "категория магазина"
    # Within food sections, the actual catalogue context beats an ingredient
    # or flavour: shrimp cream cheese stays cheese; beef noodles stay pasta.
    if priority:
        within_section = [pair for pair in matching if pair[0] == priority[0]]
        if within_section:
            return *within_section[0], 'название и продуктовый раздел магазина'
    if matching:
        return *matching[0], "название"
    if priority:
        return *priority, "категория магазина"
    return "На проверку", "На проверку", "не определено"


def excluded(name: str, category: str) -> bool:
    return bool(re.search(r"сигарет|табач|никотин|стики для нагревания|\b(?:heets|iqos|glo)\b",
                          f"{name} {category}", re.I))
